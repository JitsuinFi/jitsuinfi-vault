#!/usr/bin/env python3
"""sync-vault.py - keep the vault scalable.

Port and adaptation of ObsidianGuides/_assets/scripts/sync-vault.ps1 for this project vault:
  1. Generate _Auto-Index.md from all module folders (pattern: 2 digits + '-') and the
     support layers (Video-Workspace, Concepts, Module-Guides, Templates, Notes).
  2. Create a stub Module Guide for any module folder that lacks one (existing guides are
     never overwritten).
  3. Run the link check (target: Broken: 0).
Run whenever you add documents/modules:
    python3 scripts/sync-vault.py
"""
import datetime
import importlib.util
import re
import sys
from pathlib import Path

VAULT = Path(__file__).resolve().parent.parent
MODULE_RE = re.compile(r"^\d{2}-")
LAYERS = ["Video-Workspace", "Concepts", "Module-Guides", "Templates", "Notes"]


def load_check_links():
    spec = importlib.util.spec_from_file_location(
        "check_links", str(Path(__file__).resolve().parent / "check-links.py")
    )
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def to_title(slug):
    return " ".join(p[:1].upper() + p[1:] for p in slug.split("-") if p)


def md_files(folder):
    return sorted(p for p in folder.rglob("*.md") if ".obsidian" not in p.parts)


def link_for(path):
    return path.relative_to(VAULT).with_suffix("").as_posix()


def main():
    modules = sorted(d for d in VAULT.iterdir() if d.is_dir() and MODULE_RE.match(d.name))

    lines = [
        "---",
        "tags: [auto, index]",
        "---",
        "",
        "# _Auto-Index (generated)",
        "",
        "> Auto-generated by scripts/sync-vault.py. DO NOT edit manually - it will be overwritten on sync.",
        "> Last sync: {}".format(datetime.datetime.now().strftime("%Y-%m-%d %H:%M")),
        "",
        "## Modules",
    ]
    for m in modules:
        lines.append("")
        lines.append("### {}".format(m.name))
        for f in md_files(m):
            lines.append("- [[{}]]".format(link_for(f)))

    for layer in LAYERS:
        folder = VAULT / layer
        if not folder.is_dir():
            continue
        files = md_files(folder)
        if not files:
            continue
        lines.append("")
        lines.append("## {}".format(layer))
        for f in files:
            lines.append("- [[{}]]".format(link_for(f)))

    (VAULT / "_Auto-Index.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("OK  _Auto-Index.md generated ({} modules)".format(len(modules)))

    guide_dir = VAULT / "Module-Guides"
    guide_dir.mkdir(exist_ok=True)
    existing = [p.name for p in guide_dir.glob("*.md")]
    created = 0
    for m in modules:
        num = m.name[:2]
        if any(name.startswith(num + " ") for name in existing):
            continue
        title = to_title(m.name[3:])
        stub = [
            "---",
            "tags: [module, \"{}\"]".format(num),
            "---",
            "",
            "# {} - {}".format(num, title),
            "",
            "**Tujuan:** _TODO isi ringkasan modul._",
            "",
            "## File sumber",
        ]
        for f in md_files(m):
            stub.append("- [[{}]]".format(link_for(f)))
        stub += ["", "## Konsep kunci", "- _TODO_", ""]
        name = "{} - {}.md".format(num, title)
        (guide_dir / name).write_text("\n".join(stub), encoding="utf-8")
        print("NEW guide stub: {}".format(name))
        created += 1
    if created == 0:
        print("OK  All modules already have a guide.")

    print("")
    print("--- link check ---")
    _, n_broken = load_check_links().check()
    return 1 if n_broken else 0


if __name__ == "__main__":
    sys.exit(main())
